def load(path):
    out = {}
    for line in open(path, encoding='utf-8'):
        line = line.strip()
        if not line: continue
        o = json.loads(line)
        if o.get('deleted'): continue
        p = o['passage']
        d = out.setdefault(p, {'sa': '', 'ru': '', 'slp1': '', 'ch': o.get('chapter', '')})
        if o['seg'] == 'sa':
            d['sa'] = o.get('text', ''); d['slp1'] = o.get('slp1', '')
        elif o['seg'] == 'ru':
            d['ru'] = o.get('text', '')
    return out

C = {}
for bk, (fn, label) in FILES.items():
    C[bk] = (load(os.path.join(JSONL_DIR, fn)), label)

def verse(bk, passage):
    vs, label = C[bk]
    if passage not in vs:
        raise KeyError(f"{label} {passage} not found")
    d = vs[passage]
    return d['sa'], d['ru'], label

